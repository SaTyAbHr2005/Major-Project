describe('Hospital Identity Mapping — req.user.hospital_id reaches M9', () => {
  test('Hospital Alpha: hospital_id=HOSP-ALPHA is sent to Python adapter (not USR_hospa001)', async () => {
    const res = await request(app)
      .get('/api/v1/federation/hospital-status')
      .set('Authorization', `Bearer ${HOSP_ALPHA()}`);
    expect(res.status).toBe(200);
    // Verify the Python subprocess received the correct hospital_id
    expect(lastSpawnPayload).not.toBeNull();
    expect(lastSpawnPayload.hospital_id).toBe('HOSP-ALPHA');
    // Crucially: must NOT be the user_id
    expect(lastSpawnPayload.hospital_id).not.toBe('USR_hospa001');
  });

  test('Hospital Beta: hospital_id=HOSP-BETA is sent to Python adapter (not USR_hospb002)', async () => {
    const res = await request(app)
      .get('/api/v1/federation/hospital-status')
      .set('Authorization', `Bearer ${HOSP_BETA()}`);
    expect(res.status).toBe(200);
    expect(lastSpawnPayload).not.toBeNull();
    expect(lastSpawnPayload.hospital_id).toBe('HOSP-BETA');
    expect(lastSpawnPayload.hospital_id).not.toBe('USR_hospb002');
  });

  test('Hospital Alpha and Beta receive DIFFERENT hospital_ids — no cross-contamination', async () => {
    const resA = await request(app)
      .get('/api/v1/federation/hospital-status')
      .set('Authorization', `Bearer ${HOSP_ALPHA()}`);
    const payloadA = lastSpawnPayload;
    lastSpawnPayload = null;

    const resB = await request(app)
      .get('/api/v1/federation/hospital-status')
      .set('Authorization', `Bearer ${HOSP_BETA()}`);
    const payloadB = lastSpawnPayload;

    expect(resA.status).toBe(200);
    expect(resB.status).toBe(200);
    expect(payloadA.hospital_id).toBe('HOSP-ALPHA');
    expect(payloadB.hospital_id).toBe('HOSP-BETA');
    expect(payloadA.hospital_id).not.toBe(payloadB.hospital_id);
  });

  test('Admin has null hospital_id — hospital-status returns 400 (not 200)', async () => {
    // Admin has no hospital_id; the controller must reject before calling M9
    const res = await request(app)
      .get('/api/v1/federation/hospital-status')
      .set('Authorization', `Bearer ${ADMIN()}`);
    // Admin is blocked at requireRole (403) before hospital_id check
    expect(res.status).toBe(403);
  });

  test('Researcher has null hospital_id — blocked at role middleware (403)', async () => {
    const res = await request(app)
      .get('/api/v1/federation/hospital-status')
      .set('Authorization', `Bearer ${RESEARCHER()}`);
    expect(res.status).toBe(403);
  });

  test('M9 participant_id is the hospital_id from M1-M3 — NOT the user_id', async () => {
    // This test documents the invariant:
    // The User schema has BOTH user_id (USR_xxxx) and hospital_id (admin-defined)
    // req.user.hospital_id is what reaches M9, which matches FederationParticipant.hospital_identifier
    const res = await request(app)
      .get('/api/v1/federation/hospital-status')
      .set('Authorization', `Bearer ${HOSP_ALPHA()}`);
    expect(res.status).toBe(200);
    // Python subprocess must have been called with hospital_id, not user_id
    expect(lastSpawnPayload.hospital_id).toBe('HOSP-ALPHA');
    expect(lastSpawnPayload).not.toHaveProperty('user_id');
  });
});

